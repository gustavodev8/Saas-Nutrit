CREATE OR REPLACE FUNCTION public.create_workout_preset_from_plan_version(
  p_source_plan_version_id bigint, p_name text DEFAULT NULL
) RETURNS bigint LANGUAGE plpgsql SECURITY INVOKER SET search_path TO '' AS $function$
DECLARE
  v_source record;
  v_preset_id bigint;
  v_preset_version_id bigint;
  v_source_session record;
  v_target_session_id bigint;
BEGIN
  SELECT version_row.id, version_row.title, version_row.goal, version_row.frequency,
         version_row.valid_from, version_row.valid_until, version_row.general_notes,
         plan.patient_id, plan.workspace_id
    INTO v_source
  FROM public.workout_plan_versions AS version_row
  JOIN public.workout_plans AS plan ON plan.id = version_row.workout_plan_id
    AND plan.workspace_id IS NOT DISTINCT FROM version_row.workspace_id
  WHERE version_row.id = p_source_plan_version_id AND version_row.status IN ('draft', 'published')
  FOR SHARE OF version_row;
  IF NOT FOUND OR v_source.workspace_id IS NULL
     OR NOT public.can_manage_workout_library(v_source.workspace_id)
     OR NOT public.can_manage_clinical_patient_scope(v_source.patient_id, v_source.workspace_id) THEN
     RAISE EXCEPTION 'editable or published workout version in an authorized workspace required';
  END IF;

  INSERT INTO public.workout_presets(workspace_id, name, description, created_by)
  VALUES (v_source.workspace_id, coalesce(nullif(btrim(p_name), ''), v_source.title),
          format('Criado a partir da versão %s da ficha.', p_source_plan_version_id), auth.uid())
  RETURNING id INTO v_preset_id;
  INSERT INTO public.workout_preset_versions(
    workspace_id, preset_id, version, source_plan_version_id, title, goal,
    frequency, valid_from, valid_until, general_notes, created_by
  ) VALUES (
    v_source.workspace_id, v_preset_id, 1, p_source_plan_version_id, v_source.title,
    v_source.goal, v_source.frequency, v_source.valid_from, v_source.valid_until,
    v_source.general_notes, auth.uid()
  ) RETURNING id INTO v_preset_version_id;

  FOR v_source_session IN
    SELECT * FROM public.workout_sessions WHERE version_id = p_source_plan_version_id ORDER BY sort_order, id
  LOOP
    INSERT INTO public.workout_preset_sessions(workspace_id, version_id, title, notes, sort_order)
      VALUES (v_source.workspace_id, v_preset_version_id, v_source_session.title, v_source_session.notes, v_source_session.sort_order)
      RETURNING id INTO v_target_session_id;
    INSERT INTO public.workout_preset_exercises(
      workspace_id, session_id, name, sets, repetitions, reference_load, rest, instructions, demo_url, sort_order
    )
    SELECT v_source.workspace_id, v_target_session_id, exercise.name, exercise.sets, exercise.repetitions,
           exercise.reference_load, exercise.rest, exercise.instructions, exercise.demo_url, exercise.sort_order
    FROM public.workout_plan_exercises AS exercise WHERE exercise.session_id = v_source_session.id;
  END LOOP;
  RETURN v_preset_version_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.create_workout_preset_version(p_preset_id bigint)
RETURNS bigint LANGUAGE plpgsql SECURITY INVOKER SET search_path TO '' AS $function$
DECLARE
  v_preset public.workout_presets%ROWTYPE;
  v_parent public.workout_preset_versions%ROWTYPE;
  v_new_version_id bigint;
  v_source_session record;
  v_target_session_id bigint;
BEGIN
  SELECT * INTO v_preset FROM public.workout_presets WHERE id = p_preset_id FOR UPDATE;
  IF NOT FOUND OR v_preset.archived_at IS NOT NULL
     OR NOT public.can_manage_workout_library(v_preset.workspace_id) THEN
    RAISE EXCEPTION 'active preset in an authorized workspace required';
  END IF;
  SELECT * INTO v_parent FROM public.workout_preset_versions
  WHERE preset_id = p_preset_id AND workspace_id = v_preset.workspace_id
    AND status IN ('published', 'archived')
  ORDER BY version DESC LIMIT 1;
  IF NOT FOUND THEN RAISE EXCEPTION 'a published preset version is required before creating a new version'; END IF;

  INSERT INTO public.workout_preset_versions(
    workspace_id, preset_id, version, parent_version_id, source_plan_version_id,
    title, goal, frequency, valid_from, valid_until, general_notes, created_by
  ) VALUES (
    v_parent.workspace_id, v_parent.preset_id, v_parent.version + 1, v_parent.id,
    v_parent.source_plan_version_id, v_parent.title, v_parent.goal, v_parent.frequency,
    v_parent.valid_from, v_parent.valid_until, v_parent.general_notes, auth.uid()
  ) RETURNING id INTO v_new_version_id;

  FOR v_source_session IN
    SELECT * FROM public.workout_preset_sessions WHERE version_id = v_parent.id ORDER BY sort_order, id
  LOOP
    INSERT INTO public.workout_preset_sessions(workspace_id, version_id, title, notes, sort_order)
      VALUES (v_parent.workspace_id, v_new_version_id, v_source_session.title, v_source_session.notes, v_source_session.sort_order)
      RETURNING id INTO v_target_session_id;
    INSERT INTO public.workout_preset_exercises(
      workspace_id, session_id, catalog_exercise_id, name, sets, repetitions, reference_load, rest, instructions, demo_url, sort_order
    )
    SELECT v_parent.workspace_id, v_target_session_id, exercise.catalog_exercise_id, exercise.name,
           exercise.sets, exercise.repetitions, exercise.reference_load, exercise.rest,
           exercise.instructions, exercise.demo_url, exercise.sort_order
    FROM public.workout_preset_exercises AS exercise WHERE exercise.session_id = v_source_session.id;
  END LOOP;
  RETURN v_new_version_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.save_workout_preset_draft(
  p_preset_version_id bigint, p_title text, p_goal text, p_frequency text,
  p_valid_from date, p_valid_until date, p_general_notes text, p_sessions jsonb
) RETURNS void LANGUAGE plpgsql SECURITY INVOKER SET search_path TO '' AS $function$
DECLARE
  v_workspace_id uuid;
  v_session jsonb;
  v_exercise jsonb;
  v_session_id bigint;
  v_session_order integer := 0;
  v_exercise_order integer;
BEGIN
  IF jsonb_typeof(coalesce(p_sessions, '[]'::jsonb)) <> 'array' THEN
    RAISE EXCEPTION 'sessions must be a JSON array';
  END IF;
  UPDATE public.workout_preset_versions SET
    title = btrim(p_title), goal = coalesce(p_goal, ''), frequency = coalesce(p_frequency, ''),
    valid_from = p_valid_from, valid_until = p_valid_until,
    general_notes = coalesce(p_general_notes, '')
  WHERE id = p_preset_version_id AND status = 'draft'
  RETURNING workspace_id INTO v_workspace_id;
  IF NOT FOUND OR NOT public.can_manage_workout_library(v_workspace_id) THEN
    RAISE EXCEPTION 'editable draft in an authorized workspace required';
  END IF;

  DELETE FROM public.workout_preset_sessions WHERE version_id = p_preset_version_id;
  FOR v_session IN SELECT value FROM jsonb_array_elements(coalesce(p_sessions, '[]'::jsonb)) LOOP
    INSERT INTO public.workout_preset_sessions(workspace_id, version_id, title, notes, sort_order)
      VALUES (v_workspace_id, p_preset_version_id, coalesce(v_session->>'title',''),
        coalesce(v_session->>'notes',''), coalesce((v_session->>'sort_order')::integer, v_session_order))
      RETURNING id INTO v_session_id;
    v_exercise_order := 0;
    FOR v_exercise IN SELECT value FROM jsonb_array_elements(coalesce(v_session->'exercises','[]'::jsonb)) LOOP
      IF nullif(btrim(coalesce(v_exercise->>'name','')), '') IS NOT NULL THEN
        INSERT INTO public.workout_preset_exercises(
          workspace_id, session_id, catalog_exercise_id, name, sets, repetitions,
          reference_load, rest, instructions, demo_url, sort_order
        ) VALUES (
          v_workspace_id, v_session_id, nullif(v_exercise->>'catalog_exercise_id','')::bigint,
          btrim(v_exercise->>'name'), coalesce(v_exercise->>'sets',''), coalesce(v_exercise->>'repetitions',''),
          coalesce(v_exercise->>'reference_load',''), coalesce(v_exercise->>'rest',''),
          coalesce(v_exercise->>'instructions',''), coalesce(v_exercise->>'demo_url',''),
          coalesce((v_exercise->>'sort_order')::integer, v_exercise_order)
        );
      END IF;
      v_exercise_order := v_exercise_order + 1;
    END LOOP;
    v_session_order := v_session_order + 1;
  END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION public.publish_workout_preset_version(p_version_id bigint)
RETURNS void LANGUAGE plpgsql SECURITY INVOKER SET search_path TO '' AS $function$
DECLARE v_workspace_id uuid;
BEGIN
  SELECT workspace_id INTO v_workspace_id FROM public.workout_preset_versions
  WHERE id = p_version_id AND status = 'draft';
  IF NOT FOUND OR NOT public.can_manage_workout_library(v_workspace_id)
     OR NOT EXISTS (SELECT 1 FROM public.workout_preset_sessions WHERE version_id = p_version_id)
     OR NOT EXISTS (SELECT 1 FROM public.workout_preset_sessions AS session_row
       JOIN public.workout_preset_exercises AS exercise ON exercise.session_id = session_row.id
       WHERE session_row.version_id = p_version_id) THEN
    RAISE EXCEPTION 'draft must contain at least one session and exercise';
  END IF;
  UPDATE public.workout_preset_versions
  SET status = 'published', published_at = now()
  WHERE id = p_version_id AND status = 'draft';
  IF NOT FOUND THEN RAISE EXCEPTION 'draft was changed concurrently'; END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.create_workout_plan_from_preset(p_patient_id bigint, p_preset_version_id bigint)
RETURNS bigint LANGUAGE plpgsql SECURITY INVOKER SET search_path TO '' AS $function$
DECLARE
  v_preset public.workout_preset_versions%ROWTYPE;
  v_patient_workspace uuid;
  v_plan_id bigint;
  v_plan_version_id bigint;
  v_source_session record;
  v_target_session_id bigint;
BEGIN
  SELECT * INTO v_preset FROM public.workout_preset_versions
  WHERE id = p_preset_version_id AND status = 'published';
  SELECT workspace_id INTO v_patient_workspace FROM public.patients WHERE id = p_patient_id;
  IF NOT FOUND OR v_preset.id IS NULL OR NOT public.can_manage_workout_library(v_preset.workspace_id)
     OR v_patient_workspace IS DISTINCT FROM v_preset.workspace_id
     OR NOT public.can_manage_clinical_patient_scope(p_patient_id, v_patient_workspace) THEN
    RAISE EXCEPTION 'published preset and patient must share an authorized workspace';
  END IF;

  INSERT INTO public.workout_plans(patient_id) VALUES (p_patient_id) RETURNING id INTO v_plan_id;
  INSERT INTO public.workout_plan_versions(
    workout_plan_id, title, goal, frequency, valid_from, valid_until, general_notes,
    status, version, origin_type, source_preset_version_id
  ) VALUES (
    v_plan_id, v_preset.title, v_preset.goal, v_preset.frequency, v_preset.valid_from,
    v_preset.valid_until, v_preset.general_notes, 'draft', 1, 'preset', v_preset.id
  ) RETURNING id INTO v_plan_version_id;

  FOR v_source_session IN
    SELECT * FROM public.workout_preset_sessions WHERE version_id = p_preset_version_id ORDER BY sort_order, id
  LOOP
    INSERT INTO public.workout_sessions(version_id, title, notes, sort_order)
      VALUES (v_plan_version_id, v_source_session.title, v_source_session.notes, v_source_session.sort_order)
      RETURNING id INTO v_target_session_id;
    INSERT INTO public.workout_plan_exercises(
      session_id, name, sets, repetitions, reference_load, rest, instructions, demo_url, sort_order
    )
    SELECT v_target_session_id, exercise.name, exercise.sets, exercise.repetitions,
           exercise.reference_load, exercise.rest, exercise.instructions, exercise.demo_url, exercise.sort_order
    FROM public.workout_preset_exercises AS exercise WHERE exercise.session_id = v_source_session.id;
  END LOOP;
  RETURN v_plan_version_id;
END;
