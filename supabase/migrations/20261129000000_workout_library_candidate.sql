CREATE OR REPLACE FUNCTION public.audit_workout_library_change()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $function$
DECLARE
  v_row jsonb;
  v_old_row jsonb;
  v_workspace_id uuid;
  v_entity_id bigint;
  v_action text;
  v_fields text[];
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_row := to_jsonb(NEW);
    v_workspace_id := NEW.workspace_id;
    v_entity_id := NEW.id;
    v_action := 'create';
    SELECT COALESCE(array_agg(key ORDER BY key), ARRAY[]::text[]) INTO v_fields
    FROM jsonb_object_keys(v_row) AS item(key)
    WHERE key NOT IN ('created_at', 'updated_at');
  ELSIF TG_OP = 'UPDATE' THEN
    v_row := to_jsonb(NEW);
    v_old_row := to_jsonb(OLD);
    v_workspace_id := NEW.workspace_id;
    v_entity_id := NEW.id;
    v_action := 'update';
    SELECT COALESCE(array_agg(item.key ORDER BY item.key), ARRAY[]::text[]) INTO v_fields
    FROM jsonb_each(v_row) AS item(key, value)
    WHERE item.key NOT IN ('created_at', 'updated_at')
      AND (v_old_row -> item.key) IS DISTINCT FROM item.value;
    IF cardinality(v_fields) = 0 THEN RETURN NEW; END IF;
  ELSE
    v_row := to_jsonb(OLD);
    v_workspace_id := OLD.workspace_id;
    v_entity_id := OLD.id;
    v_action := 'delete';
    SELECT COALESCE(array_agg(key ORDER BY key), ARRAY[]::text[]) INTO v_fields
    FROM jsonb_object_keys(v_row) AS item(key)
    WHERE key NOT IN ('created_at', 'updated_at');
  END IF;

  INSERT INTO public.workout_library_audit_logs(
    workspace_id, actor_id, actor_email, action, entity_type, entity_id, changed_fields
  ) VALUES (
    v_workspace_id, auth.uid(), auth.jwt() ->> 'email', v_action, TG_TABLE_NAME, v_entity_id, v_fields
  );

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$function$;
REVOKE ALL ON FUNCTION public.audit_workout_library_change() FROM PUBLIC, anon, authenticated, service_role;

