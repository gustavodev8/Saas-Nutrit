CREATE OR REPLACE FUNCTION public.prevent_published_workout_preset_changes()
RETURNS trigger LANGUAGE plpgsql SET search_path TO '' AS $function$
DECLARE
  v_status text;
  v_parent_version integer;
  v_source_workspace uuid;
BEGIN
  IF TG_TABLE_NAME = 'workout_preset_versions' THEN
    IF TG_OP = 'DELETE' THEN
      RAISE EXCEPTION 'workout preset versions are append-only';
    END IF;
    IF TG_OP = 'UPDATE' AND (
       NEW.id IS DISTINCT FROM OLD.id
       OR NEW.workspace_id IS DISTINCT FROM OLD.workspace_id
       OR NEW.preset_id IS DISTINCT FROM OLD.preset_id
       OR NEW.version IS DISTINCT FROM OLD.version
       OR NEW.parent_version_id IS DISTINCT FROM OLD.parent_version_id
       OR NEW.source_plan_version_id IS DISTINCT FROM OLD.source_plan_version_id
       OR NEW.created_by IS DISTINCT FROM OLD.created_by
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
    ) THEN
      RAISE EXCEPTION 'workout preset version identity and lineage are immutable';
    END IF;
    IF NEW.parent_version_id IS NOT NULL THEN
      SELECT parent.version INTO v_parent_version
      FROM public.workout_preset_versions AS parent
      WHERE parent.id = NEW.parent_version_id
        AND parent.workspace_id = NEW.workspace_id
        AND parent.preset_id = NEW.preset_id;
      IF NOT FOUND OR v_parent_version >= NEW.version THEN
        RAISE EXCEPTION 'preset parent must be an earlier version of the same preset';
      END IF;
    END IF;
    IF NEW.source_plan_version_id IS NOT NULL THEN
      SELECT source.workspace_id INTO v_source_workspace
      FROM public.workout_plan_versions AS source
      WHERE source.id = NEW.source_plan_version_id AND source.status IN ('draft', 'published');
      IF NOT FOUND OR v_source_workspace IS DISTINCT FROM NEW.workspace_id THEN
        RAISE EXCEPTION 'source workout version must be editable or published and belong to the same workspace';
      END IF;
    END IF;
    IF TG_OP = 'INSERT' THEN RETURN NEW; END IF;
    IF OLD.status IN ('published', 'archived') AND NOT (
      OLD.status = 'published' AND NEW.status = 'archived'
      AND (to_jsonb(NEW) - 'status') = (to_jsonb(OLD) - 'status')
    ) THEN
      RAISE EXCEPTION 'published workout preset versions are immutable';
    END IF;
    IF OLD.status = 'archived' THEN
      RAISE EXCEPTION 'archived workout preset versions are immutable';
    END IF;
    IF OLD.status = 'draft' AND NEW.status NOT IN ('draft', 'published', 'archived') THEN
      RAISE EXCEPTION 'invalid workout preset version transition';
    END IF;
    IF OLD.status = 'draft' AND NEW.status = 'published'
       AND NEW.published_at IS NULL THEN
      RAISE EXCEPTION 'published workout preset versions require published_at';
    END IF;
    IF OLD.status = 'draft' AND NEW.status = 'published'
       AND NOT EXISTS (
         SELECT 1 FROM public.workout_preset_sessions AS session_row
         JOIN public.workout_preset_exercises AS exercise_row
           ON exercise_row.workspace_id = session_row.workspace_id AND exercise_row.session_id = session_row.id
         WHERE session_row.workspace_id = OLD.workspace_id AND session_row.version_id = OLD.id
       ) THEN
      RAISE EXCEPTION 'a workout preset needs at least one exercise before publication';
    END IF;
    RETURN NEW;
  END IF;

  IF TG_TABLE_NAME = 'workout_preset_sessions' AND TG_OP <> 'INSERT' THEN
    SELECT version_row.status INTO v_status
    FROM public.workout_preset_versions AS version_row
    WHERE version_row.id = OLD.version_id;
    IF v_status IN ('published', 'archived') THEN
      RAISE EXCEPTION 'published workout preset versions are immutable';
    END IF;
  END IF;

  IF TG_TABLE_NAME = 'workout_preset_sessions' AND TG_OP <> 'DELETE' THEN
    SELECT version_row.status INTO v_status
    FROM public.workout_preset_versions AS version_row
    WHERE version_row.id = NEW.version_id;
    IF v_status IN ('published', 'archived') THEN
      RAISE EXCEPTION 'published workout preset versions are immutable';
    END IF;
  END IF;

  IF TG_TABLE_NAME = 'workout_preset_exercises' AND TG_OP <> 'INSERT' THEN
    SELECT version_row.status INTO v_status
    FROM public.workout_preset_sessions AS session_row
    JOIN public.workout_preset_versions AS version_row ON version_row.id = session_row.version_id
    WHERE session_row.id = OLD.session_id;
    IF v_status IN ('published', 'archived') THEN
      RAISE EXCEPTION 'published workout preset versions are immutable';
    END IF;
  END IF;

  IF TG_TABLE_NAME = 'workout_preset_exercises' AND TG_OP <> 'DELETE' THEN
    SELECT version_row.status INTO v_status
    FROM public.workout_preset_sessions AS session_row
    JOIN public.workout_preset_versions AS version_row ON version_row.id = session_row.version_id
    WHERE session_row.id = NEW.session_id;
    IF v_status IN ('published', 'archived') THEN
      RAISE EXCEPTION 'published workout preset versions are immutable';
    END IF;
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$function$;

