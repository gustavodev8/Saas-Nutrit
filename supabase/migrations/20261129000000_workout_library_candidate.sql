-- LOCAL CANDIDATE ONLY. Adds a workspace-scoped exercise/preset library and
-- lineage fields without changing existing clinical RLS policies or plan rows.
DO $preflight$
BEGIN
  IF to_regclass('public.workout_plans') IS NULL
     OR to_regclass('public.workout_plan_versions') IS NULL
     OR to_regclass('public.workout_sessions') IS NULL
     OR to_regclass('public.workout_plan_exercises') IS NULL
     OR to_regclass('public.workspace_members') IS NULL
     OR to_regclass('public.workspaces') IS NULL
     OR to_regprocedure('public.can_manage_clinical_patient_scope(bigint,uuid)') IS NULL THEN
    RAISE EXCEPTION 'workout library prerequisites are missing';
  END IF;
END;
$preflight$;

CREATE OR REPLACE FUNCTION public.can_access_workout_library(p_workspace_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO '' AS $function$
  SELECT auth.role() = 'authenticated'
    AND auth.uid() IS NOT NULL
    AND p_workspace_id IS NOT NULL
    AND EXISTS (
      SELECT 1 FROM public.workspace_members AS member
      WHERE member.workspace_id = p_workspace_id
        AND member.user_id = auth.uid()
        AND member.status = 'active'
    )
    AND (SELECT count(*) FROM public.workspace_members AS active_member
         WHERE active_member.user_id = auth.uid() AND active_member.status = 'active') = 1
$function$;

CREATE OR REPLACE FUNCTION public.can_manage_workout_library(p_workspace_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO '' AS $function$
  SELECT auth.role() = 'authenticated'
    AND auth.uid() IS NOT NULL
    AND p_workspace_id IS NOT NULL
    AND EXISTS (
      SELECT 1 FROM public.workspace_members AS member
      WHERE member.workspace_id = p_workspace_id
        AND member.user_id = auth.uid()
        AND member.role IN ('owner', 'nutritionist')
        AND member.status = 'active'
    )
    AND (SELECT count(*) FROM public.workspace_members AS active_member
         WHERE active_member.user_id = auth.uid() AND active_member.status = 'active') = 1
$function$;

REVOKE ALL ON FUNCTION public.can_access_workout_library(uuid) FROM PUBLIC, anon, authenticated, service_role;
