CREATE OR REPLACE FUNCTION public.validate_workout_plan_version_lineage()
RETURNS trigger LANGUAGE plpgsql SET search_path TO '' AS $function$
DECLARE
  v_parent record;
  v_source_workspace uuid;
BEGIN
  IF TG_OP = 'UPDATE' AND (
    NEW.parent_version_id IS DISTINCT FROM OLD.parent_version_id
    OR NEW.origin_type IS DISTINCT FROM OLD.origin_type
    OR NEW.source_preset_version_id IS DISTINCT FROM OLD.source_preset_version_id
  ) THEN
    RAISE EXCEPTION 'workout version origin and lineage are immutable';
  END IF;

  IF NEW.parent_version_id IS NOT NULL THEN
    SELECT version_row.workout_plan_id, version_row.workspace_id, version_row.version
      INTO v_parent
    FROM public.workout_plan_versions AS version_row
    WHERE version_row.id = NEW.parent_version_id;
    IF NOT FOUND
       OR v_parent.workout_plan_id IS DISTINCT FROM NEW.workout_plan_id
       OR v_parent.workspace_id IS DISTINCT FROM NEW.workspace_id
       OR v_parent.version >= NEW.version THEN
      RAISE EXCEPTION 'workout parent version must be an earlier version of the same plan and workspace';
    END IF;
  END IF;

  IF NEW.origin_type = 'preset' AND NEW.source_preset_version_id IS NULL THEN
    RAISE EXCEPTION 'preset-origin workout versions require a source preset version';
  END IF;
  IF NEW.origin_type = 'version_copy' AND NEW.parent_version_id IS NULL THEN
    RAISE EXCEPTION 'copied workout versions require a parent version';
  END IF;
  IF NEW.source_preset_version_id IS NOT NULL THEN
    SELECT preset_version.workspace_id INTO v_source_workspace
    FROM public.workout_preset_versions AS preset_version
    WHERE preset_version.id = NEW.source_preset_version_id;
    IF NOT FOUND OR v_source_workspace IS DISTINCT FROM NEW.workspace_id THEN
      RAISE EXCEPTION 'workout source preset must belong to the same workspace';
    END IF;
  END IF;
  RETURN NEW;
END;
$function$;

